BEGIN
    IF to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD) AND NEW.update_time IS NOT DISTINCT FROM OLD.update_time THEN
        NEW.update_time := statement_timestamp()::timestamp(0);
    END IF;
    RETURN NEW;
END;
$$;
